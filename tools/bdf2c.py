#!/usr/bin/env python3
"""Convert a fixed-width BDF font (up to 8 px wide) into a ui_font_t C table.

Keeps code points 0x20..0xFF (ASCII plus Latin-1); anything the font lacks in
that range is left blank and flagged so the renderer can draw its fallback box.

    tools/bdf2c.py spleen-6x12.bdf font_6x12 LICENSE > src/ui/font_6x12.c

The fonts are Spleen (https://github.com/fcambus/spleen, BSD 2-Clause); the
optional third argument is the font's license file, copied into the output.
"""
import sys

FIRST, LAST = 0x20, 0xFF


def parse(path):
    glyphs, props, comments = {}, {}, []
    with open(path) as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        key, _, rest = line.partition(" ")
        if key == "COMMENT":
            comments.append(rest)
        elif key == "FONTBOUNDINGBOX":
            props["bbx"] = tuple(map(int, rest.split()))
        elif key == "FONT_ASCENT":
            props["ascent"] = int(rest)
        elif key == "STARTCHAR":
            enc, bbx, rows = None, None, []
            for line in lines:
                key, _, rest = line.partition(" ")
                if key == "ENCODING":
                    enc = int(rest)
                elif key == "BBX":
                    bbx = tuple(map(int, rest.split()))
                elif key == "BITMAP":
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(int(line[:2], 16))
                    break
            glyphs[enc] = (bbx, rows)
    return glyphs, props, comments


def main():
    path, name = sys.argv[1], sys.argv[2]
    glyphs, props, comments = parse(path)
    fw, fh, fx, fy = props["bbx"]
    if fw > 8:
        sys.exit("only fonts up to 8 px wide")
    ascent = props.get("ascent", fh + fy)

    out = []
    missing = []
    for cp in range(FIRST, LAST + 1):
        cell = [0] * fh
        if cp in glyphs:
            (w, h, x, y), rows = glyphs[cp]
            top = ascent - (y + h)  # rows from the top of the cell
            for i, bits in enumerate(rows):
                r = top + i
                if 0 <= r < fh:
                    cell[r] = (bits >> x) & 0xFF if x >= 0 else (bits << -x) & 0xFF
        else:
            missing.append(cp)
        out.append((cp, cell))

    print("// Generated by tools/bdf2c.py from %s. Do not edit." % path.split("/")[-1])
    print("//")
    for c in comments:
        c = c.strip()
        if c in ("/*", "*/"):
            continue
        print(("// " + c.lstrip("* ")).rstrip())
    if len(sys.argv) > 3:
        print("//")
        for line in open(sys.argv[3]).read().rstrip().splitlines():
            print(("// " + line).rstrip())
    print("")
    print('#include "font.h"')
    print("")
    print("static const uint8_t bits[%d * %d] = {" % (LAST - FIRST + 1, fh))
    for cp, cell in out:
        ch = chr(cp) if 0x20 < cp < 0x7F and cp != 0x5C else "U+%04X" % cp
        print("    " + ", ".join("0x%02X" % b for b in cell) + ", // " + ch)
    print("};")
    print("")
    print("// Code points the font has no glyph for (drawn as the fallback box).")
    print("static const uint8_t missing[%d] = {" % ((LAST - FIRST + 1 + 7) // 8))
    mask = [0] * ((LAST - FIRST + 1 + 7) // 8)
    for cp in missing:
        mask[(cp - FIRST) >> 3] |= 1 << ((cp - FIRST) & 7)
    print("    " + ", ".join("0x%02X" % m for m in mask) + ",")
    print("};")
    print("")
    print("const ui_font_t %s = {" % name)
    print("    .w = %d, .h = %d, .first = 0x%02X, .last = 0x%02X," % (fw, fh, FIRST, LAST))
    print("    .bits = bits, .missing = missing,")
    print("};")


main()
